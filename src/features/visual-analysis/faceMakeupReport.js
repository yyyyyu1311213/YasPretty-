const sections = [['brow', '眉妆', 'brow'], ['eyes', '眼妆', 'eyes'], ['nose', '鼻部修容', 'nose'], ['cheeks', '腮红布局', 'contour'], ['contour', '脸部修容', 'contour']]

export function buildFaceMakeupReport(features) {
  return sections.map(([id, title, featureId]) => {
    const feature = features.find((entry) => entry.id === featureId)
    const supported = feature && Object.hasOwn(FEATURE_OPTIONS[featureId], feature.code)
    const specific = supported && techniques[id][feature.code]
    return { id, title, featureId,
      basis: specific ? feature.value : '该部位未采用形态结论',
      source: specific ? feature.source === 'user' ? '依据你的选择' : '依据照片估算' : '通用建议',
      style: specific ? looks[id][feature.code][0] : '', finish: specific ? looks[id][feature.code][1] : '',
      technique: specific ? specific[0] : general[id],
      reason: specific ? specific[1] : '目前信息不足，先提供不依赖形态分类的基础手法，避免按不确定结论调整妆容。' }
  })
}
