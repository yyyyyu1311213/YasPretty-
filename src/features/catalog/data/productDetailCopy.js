/** 只生成通用操作建议；参数中的限制与版本提醒另行保留。 */
export function getDetailCautions(product, record) {
  const cautions = [...(categoryCautions[product.category] || product.cautions || [])]
  const facts = record?.parameterFacts || []
  if (facts.some(f => /敏感肌除外/.test(f.value))) cautions.push('商品说明不建议敏感肌使用；眼周容易敏感时请避开这款。')
  if (facts.some(f => /防水/.test(f.label))) cautions.push('标注防水也不代表不会晕染，第一次用先观察自己的带妆情况。')
  if (facts.some(f => /防晒/.test(f.label))) cautions.push('轻薄上妆不等于足量防晒，日常防晒仍需单独安排。')
  if (facts.some(f => /储存/.test(f.label))) cautions.push('用后盖好，放在阴凉干燥处，避开阳光直射。')
  if (record?.dataIssues?.length) cautions.push('下单时核对版本和规格，页面里可能同时列有不同选项。')
  return cautions
}
