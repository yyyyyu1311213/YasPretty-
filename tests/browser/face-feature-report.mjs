// Real local reconstruction. The manual choices below test correction, not accuracy.
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
const { chromium } = await import(process.env.YAS_QA_PLAYWRIGHT_MODULE || '../../.qa/playwright/node_modules/playwright/index.mjs')
const baseURL = process.env.YAS_QA_BASE_URL || 'http://127.0.0.1:5175'
const output = path.resolve('.qa/face-feature-report')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
try {
  for (const width of [1440, 360]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    const errors = [], posted = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('request', (request) => { if (request.method() === 'POST') posted.push(request.url()) })
    await page.goto(`${baseURL}/face-study`)
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find((b) => b.textContent === 'DECA')?.disabled)
    await page.getByRole('button', { name: 'DECA', exact: true }).click()
    await page.getByLabel('我同意将照片交由本机后端进行本次分析').check()
    const storageBefore = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))
    const response = page.waitForResponse((r) => r.url().endsWith('/api/face-reconstruction/deca') && r.request().method() === 'POST', { timeout: 70000 })
    await page.getByLabel('选择人脸照片').setInputFiles('.qa/hairline/1.jpg')
    const api = await response; assert.equal(api.status(), 200)
    assert.equal((await api.json()).result.engine, 'DECA')
    await page.locator('.face-stage.is-centered').waitFor({ timeout: 60000 })
    assert.equal(await page.locator('.face-feature-report').count(), 1)
    assert.equal(await page.getByRole('checkbox').count(), 1, 'upload consent is the only gate')
    assert.equal(await page.locator('.face-leaders circle').count(), 3)
    const thirds = page.locator('[data-feature="thirds"]')
    await thirds.getByText('三庭比例', { exact: true }).waitFor()
    assert.equal(await thirds.locator('.face-thirds-values b').count(), 3)
    await thirds.getByRole('button', {name:'发际线不贴合，跳过此项'}).click()
    await page.locator('.face-thirds-label').getByText('三庭比例已跳过').waitFor()
    assert.equal(await thirds.locator('.face-product').count(), 0)
    await thirds.getByRole('button', {name:'恢复比例参考'}).click()
    assert.equal(await page.locator('[data-feature="lips"]').count(), 0)
    const eyes = page.locator('[data-feature="eyes"]')
    await page.getByLabel('修正眼型与眼距').selectOption('almond')
    assert((await eyes.innerText()).includes('柔棕渐层'))
    assert.equal(await eyes.locator('.face-product').count(),3)
    await page.getByLabel('修正眼型与眼距').selectOption('elongated')
    const eyePlan = await eyes.locator('.face-feature-plan').innerText()
    assert(eyePlan.includes('睫毛膏'))
    const list = eyes.locator('.face-product')
    const name = await list.first().getAttribute('aria-label')
    await list.first().click()
    const detail = page.getByRole('dialog', {name: name.slice(2) + ' 产品详情'})
    await detail.waitFor()
    await detail.getByRole('button',{name:'关闭详情'}).click()
    assert.equal(await page.getByLabel('修正眼型与眼距').inputValue(),'elongated')
    await page.getByLabel('选择脸型').selectOption('square')
    assert((await page.locator('[data-feature="contour"] .face-feature-plan').innerText()).includes('下颌外角'))
    assert.equal(await eyes.locator('.face-feature-plan').innerText(), eyePlan)
    const obs = await eyes.locator('.face-feature-observation').boundingBox()
    const plan = await eyes.locator('.face-feature-plan').boundingBox()
    assert(width === 360 ? plan.y >= obs.y + obs.height - 1 : plan.x >= obs.x + obs.width - 1)
    await eyes.screenshot({path:path.join(output, width+'-paired.png')})
    await page.getByLabel('修正眼型与眼距').selectOption('occluded')
    assert.equal(await list.count(), 0)
    assert.equal(posted.length,1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
    await page.getByRole('button', {name:'3DDFA_V2',exact:true}).click()
    await page.locator('.face-stage.is-centered').waitFor({timeout:70000})
    assert.equal(await page.getByLabel('选择脸型').inputValue(),'auto')
    await page.getByRole('button', {name:'DECA',exact:true}).click()
    await page.locator('.face-stage.is-centered').waitFor()
    assert.equal(await page.getByLabel('修正眼型与眼距').inputValue(),'auto')
    assert.equal(posted.length,2)
    await page.getByLabel('选择人脸照片').setInputFiles('.qa/hairline/1112.jpg')
    await page.locator('.face-thirds-label').getByText('三庭比例检测失败').waitFor({timeout:70000})
    assert((await page.locator('.face-thirds-label').innerText()).includes('未找到连续清晰的中央发际线'))
    await page.locator('.face-model-area').screenshot({path:path.join(output,width+'-thirds-failure.png')})
    await page.getByRole('button', { name: '删除照片与结果', exact: true }).click()
    assert.equal(await page.locator('.face-feature-report,.face-stage').count(), 0)
    assert.equal(await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } })), storageBefore)
    assert(posted.every((url) => url.startsWith(`${baseURL}/api/face-reconstruction`)))
    assert.deepEqual(errors, [])
    await context.close()
  }
  console.log('Real dual-engine thirds, paired local plans, corrections, product details and mobile layout passed.')
} finally { await browser.close() }
